#!/usr/bin/env sh
#
# Capture the GNOME desktop settings I have changed into desktop-settings.dconf.
# Extension settings are captured separately by dump-extensions.sh.
#
# Deliberately left out:
#   - the wallpaper path: bootstrap.sh sets it from wallpapers/ instead
#   - night-light coordinates: a precise location, and this repo is public
#   - enabled-extensions: owned by extensions.txt / install-extensions.sh

set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
out="$here/desktop-settings.dconf"

# Whole dconf directories, captured as-is and rebased under /org/gnome/.
dirs='
desktop/interface
desktop/wm/preferences
desktop/wm/keybindings
desktop/peripherals/touchpad
desktop/peripherals/mouse
mutter
settings-daemon/plugins/media-keys
shell/keybindings
'

dump_dir() {
  dconf dump "/org/gnome/$1/" | awk -v p="$1" '
    /^\[\/\]$/   { print "[" p "]"; next }
    /^\[.*\]$/   { sub(/^\[/, "[" p "/"); print; next }
                 { print }'
}

# Single keys, from directories that otherwise hold machine-specific state.
dump_key() {
  value=$(dconf read "/org/gnome/$1/$2")
  [ -n "$value" ] && printf '[%s]\n%s=%s\n\n' "$1" "$2" "$value"
  return 0
}

{
  printf '# GNOME desktop settings. Load with:\n'
  printf '#   dconf load /org/gnome/ < gnome/desktop-settings.dconf\n'
  printf '# Generated by gnome/dump-desktop.sh; re-run it instead of editing by hand.\n\n'

  for d in $dirs; do
    dump_dir "$d"
    echo
  done

  dump_key shell favorite-apps
  dump_key desktop/input-sources sources
  dump_key nautilus/preferences default-folder-viewer
} > "$out"

printf 'Wrote %s\n' "$out"
printf 'Review the diff for personal data before committing.\n'
